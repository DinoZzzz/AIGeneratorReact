import { expect, test } from '@playwright/test';
import { installManagementFixture, loginManagement } from './helpers/managementFixture';

// Stateful API fixtures exercise actual browser forms and reloads. These tests
// validate client behavior, not deployed Supabase policies or production data.
test('customer and construction create, edit and delete persist across reloads', async ({ context, page }) => {
    const fixture = await installManagementFixture(context);
    await loginManagement(page);
    await page.goto('/customers');
    await page.getByRole('link', { name: 'Novi naručitelj', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Novi naručitelj' })).toBeVisible();
    await page.locator('input[name="work_order"]').fill('E2E-001');
    await page.locator('input[name="name"]').fill('E2E Naručitelj');
    await page.locator('input[name="location"]').fill('Zagreb');
    await page.locator('input[name="address"]').fill('Testna 12');
    await page.locator('input[name="postal_code"]').fill('10000');
    await page.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page).toHaveURL(/\/customers$/);
    expect(fixture.tables.customers).toHaveLength(1);
    const customerId = fixture.tables.customers[0].id;
    await page.reload();
    await page.locator('tr').filter({ hasText: 'E2E Naručitelj' }).getByTitle('Uredi', { exact: true }).click();
    await expect(page.locator('input[name="postal_code"]')).toHaveValue('10000');
    await page.locator('input[name="address"]').fill('Nova 15');
    await page.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page).toHaveURL(/\/customers$/);
    expect(fixture.tables.customers[0].address).toBe('Nova 15');
    await page.goto(`/customers/${customerId}/constructions`);
    await page.getByRole('link', { name: 'Novo gradilište', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Novo gradilište' })).toBeVisible();
    await page.locator('input[name="work_order"]').fill('G-001');
    await page.locator('input[name="name"]').fill('E2E Gradilište');
    await page.locator('input[name="location"]').fill('Sesvete');
    await page.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`/customers/${customerId}/constructions$`));
    expect(fixture.tables.constructions).toHaveLength(1);
    await page.reload();
    await page.locator('tr').filter({ hasText: 'E2E Gradilište' }).getByTitle('Uredi', { exact: true }).click();
    await page.locator('input[name="name"]').fill('E2E Gradilište izmjena');
    await page.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`/customers/${customerId}/constructions$`));
    expect(fixture.tables.constructions[0].name).toBe('E2E Gradilište izmjena');
    await page.reload();
    await page.locator('tr').filter({ hasText: 'E2E Gradilište izmjena' }).getByTitle('Obriši', { exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Potvrdi', exact: true }).click();
    await expect.poll(() => fixture.tables.constructions.length).toBe(0);
    await page.reload();
    await expect(page.getByText('E2E Gradilište izmjena', { exact: true })).toHaveCount(0);
    await page.goto('/customers');
    await page.locator('tr').filter({ hasText: 'E2E Naručitelj' }).getByTitle('Akcije', { exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Potvrdi', exact: true }).click();
    await expect.poll(() => fixture.tables.customers.length).toBe(0);
    await page.reload();
    await expect(page.getByText('E2E Naručitelj', { exact: true })).toHaveCount(0);
});

