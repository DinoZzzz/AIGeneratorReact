test('calendar rejects invalid time range and preserves the form after denied writes', async ({ context, page }) => {
    const fixture = await installManagementFixture(context);
    await loginManagement(page);
    await page.goto('/calendar');
    await page.getByRole('button', { name: 'Novi Termin', exact: true }).click();
    await page.locator('#title').fill('E2E Oporavak termina');
    const start = await page.locator('#start').inputValue();
    await page.locator('#end').fill(start);
    await page.getByRole('dialog').getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page.getByText('Kraj termina mora biti nakon početka.', { exact: true })).toBeVisible();
    expect(fixture.tables.calendar_events).toHaveLength(0);
    const end = new Date(`${start}:00`);
    end.setHours(end.getHours() + 1);
    const endLocal = `${end.getFullYear()}-${String(end.getMonth() + 1).padStart(2, '0')}-${String(end.getDate()).padStart(2, '0')}T${String(end.getHours()).padStart(2, '0')}:${String(end.getMinutes()).padStart(2, '0')}`;
    await page.locator('#end').fill(endLocal);
    fixture.setCalendarFailure('POST');
    await page.getByRole('dialog').getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page.getByText('Termin nije spremljen. Provjerite podatke i pokušajte ponovno.', { exact: true })).toBeVisible();
    await expect(page.locator('#title')).toHaveValue('E2E Oporavak termina');
    expect(fixture.tables.calendar_events).toHaveLength(0);
    fixture.setCalendarFailure();
    await page.getByRole('dialog').getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    expect(fixture.tables.calendar_events).toHaveLength(1);
    await page.locator('.rbc-event').filter({ hasText: 'E2E Oporavak termina' }).click();
    fixture.setCalendarFailure('DELETE');
    await page.getByRole('dialog').getByRole('button', { name: 'Obriši', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Obriši', exact: true }).click();
    await expect(page.getByText('Termin nije obrisan. Pokušajte ponovno.', { exact: true })).toBeVisible();
    expect(fixture.tables.calendar_events).toHaveLength(1);
    fixture.setCalendarFailure();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Obriši', exact: true }).click();
    await expect.poll(() => fixture.tables.calendar_events.length).toBe(0);
});

