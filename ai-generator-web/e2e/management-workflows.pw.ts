    await certifiers.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(certifiers.locator('form')).toHaveCount(0);
    expect(fixture.tables.certifiers).toHaveLength(1);
    await openAdministration();
    await expect(certifiers.getByText('E2E Certifikator dipl.ing.', { exact: true })).toBeVisible();
    await certifiers.getByTitle('Uredi', { exact: true }).click();
    await certifiers.getByPlaceholder('npr. Ivan Horvat', { exact: true }).fill('E2E Certifikator izmjena');
    await certifiers.getByRole('button', { name: 'Spremi', exact: true }).click();
    await expect(certifiers.locator('form')).toHaveCount(0);
    expect(fixture.tables.certifiers[0].name).toBe('E2E Certifikator izmjena');
    await openAdministration();
